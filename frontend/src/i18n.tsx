function readStoredLanguage(): PortalLanguage {
  try {
    return localStorage.getItem(languageStorageKey) === "hi" ? "hi" : "en"
  } catch {
    return "en"
  }
}

i18n.use(initReactI18next).init({
  resources,
  lng: readStoredLanguage(),
  fallbackLng: "en",
  interpolation: { escapeValue: false },
})

type LanguageContextValue = {
  language: PortalLanguage
  setLanguage: (language: PortalLanguage) => void
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<PortalLanguage>(readStoredLanguage)

  useEffect(() => {
    void i18n.changeLanguage(language)
    document.documentElement.lang = language === "hi" ? "hi" : "en"
    document.documentElement.dataset.language = language

    try {
      localStorage.setItem(languageStorageKey, language)
    } catch {
      // The setting remains active for the current session if storage is unavailable.
    }
  }, [language])

  const value = useMemo(() => ({ language, setLanguage: setLanguageState }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function usePortalLanguage() {
  const context = useContext(LanguageContext)

  if (!context) {
    throw new Error("usePortalLanguage must be used within LanguageProvider")
  }

  return context
}

export default i18n
